-- =====================================================================
-- BriefCase - Diagnostic & Server Environment Inspection Script
-- Execute in MySQL Workbench to verify environment and schema status
-- =====================================================================

-- 1. Check Server Version and Storage Engines
SELECT VERSION() AS mysql_version, CURRENT_USER() AS connected_as, NOW() AS server_time;
SHOW ENGINES;

-- 2. Check if Briefcase Database Exists
SHOW DATABASES LIKE 'briefcase';

-- 3. Check Tables in Briefcase Database
USE briefcase;
SHOW FULL TABLES;

-- 4. Count Records Across All 20 Entities
SELECT 'CLIENT' AS table_name, COUNT(*) AS record_count FROM CLIENT
UNION ALL SELECT 'DEPARTMENT', COUNT(*) FROM DEPARTMENT
UNION ALL SELECT 'CASE_TYPE', COUNT(*) FROM CASE_TYPE
UNION ALL SELECT 'CASE_STATUS', COUNT(*) FROM CASE_STATUS
UNION ALL SELECT 'DOCUMENT_TYPE', COUNT(*) FROM DOCUMENT_TYPE
UNION ALL SELECT 'PAYMENT_METHOD', COUNT(*) FROM PAYMENT_METHOD
UNION ALL SELECT 'COURT', COUNT(*) FROM COURT
UNION ALL SELECT 'USERS', COUNT(*) FROM USERS
UNION ALL SELECT 'LAWYER', COUNT(*) FROM LAWYER
UNION ALL SELECT 'PARTY', COUNT(*) FROM PARTY
UNION ALL SELECT 'CASES', COUNT(*) FROM CASES
UNION ALL SELECT 'CASE_LAWYER', COUNT(*) FROM CASE_LAWYER
UNION ALL SELECT 'CASE_PARTY', COUNT(*) FROM CASE_PARTY
UNION ALL SELECT 'APPOINTMENT', COUNT(*) FROM APPOINTMENT
UNION ALL SELECT 'DOCUMENT', COUNT(*) FROM DOCUMENT
UNION ALL SELECT 'HEARING', COUNT(*) FROM HEARING
UNION ALL SELECT 'INVOICE', COUNT(*) FROM INVOICE
UNION ALL SELECT 'PAYMENT', COUNT(*) FROM PAYMENT
UNION ALL SELECT 'CASE_STATUS_HISTORY', COUNT(*) FROM CASE_STATUS_HISTORY
UNION ALL SELECT 'TASK', COUNT(*) FROM TASK;

-- 5. Check Active Foreign Keys and Constraints on CASES and CLIENT
SELECT 
    TABLE_NAME, 
    COLUMN_NAME, 
    CONSTRAINT_NAME, 
    REFERENCED_TABLE_NAME, 
    REFERENCED_COLUMN_NAME
FROM 
    INFORMATION_SCHEMA.KEY_COLUMN_USAGE
WHERE 
    TABLE_SCHEMA = 'briefcase' 
    AND REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY TABLE_NAME;
